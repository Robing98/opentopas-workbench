def csda_cm(nucleons, charge, e_u):
    """Rough water range [cm]: Bragg-Kleeman for protons, scaled with A/Z^2."""
    if nucleons == 0:
        return 0.5 * e_u / 2.0 + 1  # electrons: about 0.5 cm per MeV
    return 0.0022 * e_u ** 1.77 * nucleons / charge ** 2


def parse_energies(s):
    out = []
    for tok in str(s).replace(";", ",").split(","):
        tok = tok.strip()
        if tok:
            v = float(tok)
            if v <= 0: raise ValueError(f"energy must be positive: {tok}")
            out.append(v)
    if not out: raise ValueError("no energies given")
    return out


def num(v): return f"{v:g}"


def generate(v):
    files = []
    side, gap, bin_mm = float(v["side"]), float(v["gap"]), float(v["bin"])
    for key in v.get("particles") or []:
        part, a, z, label = PARTICLES[key]
        for e in parse_energies(v["energies"]):
            total = e * (a or 1)
            depth = max(4.0, math.ceil(csda_cm(a, z, e) * 1.2 + 2))
            depth = min(depth, 100.0)
            nbins = max(1, int(round(depth * 10 / bin_mm)))
            name = f"{v['prefix']}_{key}{num(e).replace('.', 'p')}"
            hlz_world = (depth + gap) / 2 + 5
            t = f"""# {label['en']} {num(e)} MeV/u ({num(total)} MeV total) into {v['material']}. Generated by OpenTOPAS Workbench (pencil_beam).
# Phantom entrance at z = 0, beam along -z from {num(gap)} cm upstream. Depth bin 0 = entrance.
i:Ts/NumberOfThreads            = 0
i:Ts/ShowHistoryCountAtInterval = {max(1000, int(v['histories']) // 10)}
b:Ts/PauseBeforeQuit            = "False"
s:Ge/World/Material = "{v['world']}"
d:Ge/World/HLX      = {num(side / 2 + 5)} cm
d:Ge/World/HLY      = {num(side / 2 + 5)} cm
d:Ge/World/HLZ      = {num(hlz_world + depth / 2)} cm

s:Ge/Phantom/Type     = "TsBox"
s:Ge/Phantom/Parent   = "World"
s:Ge/Phantom/Material = "{v['material']}"
d:Ge/Phantom/HLX      = {num(side / 2)} cm
d:Ge/Phantom/HLY      = {num(side / 2)} cm
d:Ge/Phantom/HLZ      = {num(depth / 2)} cm
d:Ge/Phantom/TransZ   = -{num(depth / 2)} cm
d:Ge/Phantom/RotX     = 180. deg
i:Ge/Phantom/ZBins    = {nbins}

d:Ge/BeamPosition/TransZ = {num(gap)} cm
s:So/Demo/BeamParticle           = "{part}"
d:So/Demo/BeamEnergy             = {num(total)} MeV
u:So/Demo/BeamEnergySpread       = {num(float(v['spread']))}
s:So/Demo/BeamPositionDistribution = "Gaussian"
d:So/Demo/BeamPositionSpreadX    = {num(float(v['sigma']))} mm
d:So/Demo/BeamPositionSpreadY    = {num(float(v['sigma']))} mm
d:So/Demo/BeamAngularSpreadX     = 1.0 mrad
d:So/Demo/BeamAngularSpreadY     = 1.0 mrad
i:So/Demo/NumberOfHistoriesInRun = {int(v['histories'])}

s:Sc/Depth/Quantity   = "{v['quantity']}"
s:Sc/Depth/Component  = "Phantom"
s:Sc/Depth/OutputType = "csv"
s:Sc/Depth/IfOutputFileAlreadyExists = "Overwrite"
s:Sc/Depth/OutputFile = "{name}_depth"
"""
            if v.get("map2d"):
                t += f"""
# 2D map: a parallel world copy of the phantom with lateral x binning
s:Ge/Map/Type     = "TsBox"
s:Ge/Map/Parent   = "World"
b:Ge/Map/IsParallel = "True"
s:Ge/Map/Material = "{v['material']}"
d:Ge/Map/HLX      = {num(min(side / 2, 5))} cm
d:Ge/Map/HLY      = {num(side / 2)} cm
d:Ge/Map/HLZ      = {num(depth / 2)} cm
d:Ge/Map/TransZ   = -{num(depth / 2)} cm
d:Ge/Map/RotX     = 180. deg
i:Ge/Map/XBins    = {int(round(min(side, 10) * 10))}
i:Ge/Map/ZBins    = {nbins}
s:Sc/Map/Quantity   = "{v['quantity']}"
s:Sc/Map/Component  = "Map"
s:Sc/Map/OutputType = "csv"
s:Sc/Map/IfOutputFileAlreadyExists = "Overwrite"
s:Sc/Map/OutputFile = "{name}_map"
"""
            if total > 500 and not part.startswith("GenericIon"):
                t += "\n# Total kinetic energy above the default EM table range for this particle (500 MeV in TOPAS 3.9, 600 MeV in OpenTOPAS).\nd:Ph/Default/EMRangeMax = " + num(max(1000, math.ceil(total * 1.2 / 100) * 100)) + " MeV\n"
            files.append((name + ".txt", t))
    if not files: raise ValueError("select at least one particle")
    return files
